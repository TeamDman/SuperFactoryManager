#[test]
fn pointer_owner_toggles_independently_from_unrelated_existing_features() -> Result<()> {
    let fixture = Fixture::load()?;
    let mut masks = 0;
    for target in &TARGETS[..2] {
        for mask in 0_u8..8 {
            let mut enabled = Vec::new();
            for (index, owner) in [OWNER, "workspace_panels", "client_overlay_input"]
                .iter()
                .enumerate()
            {
                if mask & (1 << index) != 0 {
                    enabled.push(*owner);
                }
            }
            let context = fixture.core.context(target, &enabled)?;
            assert_eq!(
                fixture.render(&context)?.as_deref(),
                (mask & 1 != 0).then_some(fixture.raw.as_slice()),
            );
            let selected =
                select_core_inputs(&fixture.core.metadata, &context, &fixture.inventory)?;
            if let Some(input) = selected.inputs.get(PATH) {
                assert_eq!(input.input, PATH);
                assert!(input.template);
            }
            assert!(!context.features["workspace_panel_move_gestures"]);
            masks += 1;
        }
    }
    assert_eq!(masks, 16);
    Ok(())
}

