#[test]
fn pointer_actual_caller_guards_and_threadlocal_restoration_source_contract_remain() -> Result<()> {
    let fixture = Fixture::load()?;
    let body = std::str::from_utf8(&fixture.raw)?;
    for marker in [
        "private static final ThreadLocal<Integer> CURRENT = new ThreadLocal<>();",
        "public static void begin(int modifiers) { CURRENT.set(modifiers); }",
        "public static void end() { CURRENT.remove(); }",
        "value == null ? OptionalInt.empty() : OptionalInt.of(value)",
        "value == null ? physicalFallback.getAsBoolean() : (value & mask) != 0",
        "Integer previous = CURRENT.get();",
        "try { return operation.get(); }",
        "finally { if (previous == null) end(); else begin(previous); }",
    ] {
        assert!(
            body.contains(marker),
            "genuine pointer contract changed: {marker}"
        );
    }
    for forbidden in [
        "net.minecraft.",
        "org.lwjgl.",
        "java.nio.file.",
        "ProcessBuilder",
        "SFMPacket",
    ] {
        assert!(
            !body.contains(forbidden),
            "pointer leaf gained an external/effect dependency"
        );
    }
    let mouse = String::from_utf8(fixture.core.read_source(MOUSE)?)?;
    let multiplexer = String::from_utf8(fixture.core.read_source(MULTIPLEXER)?)?;
    let begin = mouse
        .find("SFMPointerInputModifiers.begin(modifiers)")
        .expect("actual ingress");
    let gate = mouse[..begin]
        .rfind("{% if features.pointer_modifier_ingress %}")
        .expect("actual ingress owner gate");
    assert!(!mouse[gate..begin].contains("{% endif %}"));
    let call = multiplexer
        .find("ca.teamdman.sfm.client.input.SFMPointerInputModifiers.isDown(")
        .expect("actual workspace caller");
    let move_gate = multiplexer[..call]
        .rfind("{% if features.workspace_panel_move_gestures %}")
        .expect("actual move owner gate");
    assert!(!multiplexer[move_gate..call].contains("{% endif %}"));
    assert!(multiplexer[call..].starts_with(
        "ca.teamdman.sfm.client.input.SFMPointerInputModifiers.isDown(\n                                GLFW.GLFW_MOD_ALT, Screen::hasAltDown)"
    ));
    for target in &TARGETS[..2] {
        for mask in 0_u8..16 {
            let mut enabled = Vec::new();
            if mask & 1 != 0 {
                enabled.push(OWNER);
            }
            if mask & 2 != 0 {
                enabled.push("client_overlay_input");
            }
            if mask & 4 != 0 {
                enabled.push("client_overlay_scenes");
            }
            if mask & 8 != 0 {
                enabled.push("workspace_panels");
            }
            let context = fixture.core.context(target, &enabled)?;
            let rendered = render_java_source(&mouse, &context)?;
            assert_eq!(
                rendered.contains("SFMPointerInputModifiers.begin("),
                mask & 1 != 0
            );
            assert_eq!(
                rendered.contains("SFMPointerInputModifiers.end()"),
                mask & 1 != 0
            );
            assert_eq!(
                rendered.contains("SFMClientOverlayRuntime.get().mouseButton("),
                mask & 14 == 14
            );
            assert_eq!(
                rendered.contains("finishSfmPointerModifiers("),
                mask & 1 != 0
            );
            if mask == 15 {
                assert!(rendered.contains("catch (RuntimeException | Error failure)"));
                assert!(rendered.contains("callback.cancel();"));
            }
        }
    }
    Ok(())
}

#[test]
fn pointer_real_collector_ignores_poison_when_off_and_emits_owned_bannered_body_when_on()
-> Result<()> {
    let fixture = Fixture::load()?;
    let temp = tempfile::tempdir()?;
    let core_root = temp.path().join(CORE_ROOT);
    std::fs::create_dir_all(&core_root)?;
    let mut metadata = fixture.core.metadata.clone();
    metadata.source_rules.retain(|path, _| path == PATH);
    let inventory = BTreeSet::from([PATH.to_owned()]);
    // A real edit of the one shared authored body must reach both D2 outputs.
    let common_source_edit = format!(
        "// shared pointer core propagation witness\n{}",
        std::str::from_utf8(&fixture.raw)?,
    );
    for target in &TARGETS[..2] {
        let off = fixture.core.context(target, &[])?;
        let off_selection = select_core_inputs(&metadata, &off, &inventory)?;
        assert!(!off_selection.inputs.contains_key(PATH));
        for (output, input) in &off_selection.inputs {
            ensure!(
                !output.starts_with("src/"),
                "unexpected isolated Java input"
            );
            let source = read_bounded(
                &checked_file(&fixture.core.core, &input.input)?,
                16 * 1024 * 1024,
            )?;
            let destination = core_root.join(&input.input);
            std::fs::create_dir_all(destination.parent().expect("portable project input"))?;
            std::fs::write(destination, source)?;
        }
        let destination = core_root.join(PATH);
        std::fs::create_dir_all(destination.parent().expect("portable source input"))?;
        std::fs::write(&destination, [0xff, 0xfe])?;
        let off_artifacts = collect_core_artifacts(&core_root, &off_selection, &off)?;
        assert!(!off_artifacts.contains_key(PATH));
        for output in PROJECT_FILES {
            assert!(off_artifacts.contains_key(output));
        }
        let on = fixture.core.context(target, &[OWNER])?;
        let on_selection = select_core_inputs(&metadata, &on, &inventory)?;
        assert!(on_selection.inputs[PATH].template);
        assert!(collect_core_artifacts(&core_root, &on_selection, &on).is_err());
        std::fs::write(&destination, &fixture.raw)?;
        let artifacts = collect_core_artifacts(&core_root, &on_selection, &on)?;
        let artifact = &artifacts[PATH];
        let rendered = render_java_source(std::str::from_utf8(&fixture.raw)?, &on)?;
        assert_eq!(artifact.source_bytes, fixture.raw);
        assert_eq!(artifact.source_path, format!("{CORE_ROOT}/{PATH}"));
        assert!(artifact.overlay.is_none());
        assert_eq!(
            artifact.output_bytes,
            format!("{BANNER}{rendered}").as_bytes()
        );
        assert_eq!(std::fs::read(&destination)?, fixture.raw);
        std::fs::write(&destination, common_source_edit.as_bytes())?;
        let changed = collect_core_artifacts(&core_root, &on_selection, &on)?;
        let changed_pointer = &changed[PATH];
        let changed_rendered = render_java_source(&common_source_edit, &on)?;
        assert_eq!(changed_pointer.source_bytes, common_source_edit.as_bytes());
        assert_eq!(changed_pointer.source_path, format!("{CORE_ROOT}/{PATH}"));
        assert!(changed_pointer.overlay.is_none());
        assert_eq!(
            changed_pointer.output_bytes,
            format!("{BANNER}{changed_rendered}").as_bytes(),
        );
        assert!(changed_rendered.starts_with("// shared pointer core propagation witness\n"));
        // Only the temp collector input was changed, never canonical core/history.
        assert_eq!(fixture.core.read_source(PATH)?, fixture.raw);
        std::fs::write(&destination, &fixture.raw)?;
    }
    Ok(())
}
