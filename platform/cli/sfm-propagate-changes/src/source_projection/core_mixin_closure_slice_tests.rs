fn normalize_raw(bytes: &[u8], fixed: Golden) -> Result<Vec<u8>> {
    ensure!(
        bytes.len() == fixed.raw_bytes && sha256(bytes) == fixed.raw_sha256,
        "mixin raw witness hash or length drift"
    );
    let text = std::str::from_utf8(bytes)?;
    ensure!(
        !text.starts_with('\u{feff}')
            && text.ends_with('\n') == fixed.raw_final_lf
            && text.matches("\r\n").count() == fixed.crlf
            && !text.replace("\r\n", "").contains('\r'),
        "mixin raw newline or BOM drift"
    );
    let mut normalized = text.replace("\r\n", "\n").into_bytes();
    if fixed.append_lf {
        ensure!(!fixed.raw_final_lf, "unapproved duplicate terminal LF");
        normalized.push(b'\n');
    }
    ensure!(
        normalized.len() == fixed.normalized_bytes
            && sha256(&normalized) == fixed.normalized_sha256,
        "mixin normalization exceeded exact approval"
    );
    Ok(normalized)
}
// Preserve the complete historical resource pin and all original raw/golden
// witnesses; recover it by reversing exactly the one reviewed current guard.
fn verify_current_template(bytes: &[u8], selected_source: Source) -> Result<()> {
    if selected_source.path == SOURCES[1].path || selected_source.path == SOURCES[3].path {
        let (size, digest) = if selected_source.path == SOURCES[1].path {
            (
                4198,
                "sha256:1fa8816cb01467c6667e0a377d0c6d433e13db391b67722df0e0b41aa4a631b5",
            )
        } else {
            (
                2671,
                "sha256:ae8f390a903ff0dfba174923845108eca89b128818f5df4a401685b31939afb0",
            )
        };
        ensure!(
            bytes.len() == size && sha256(bytes) == digest,
            "current ingress template drift"
        );
        let mut original = std::str::from_utf8(bytes)?.to_owned();
        let pair = "{% if features.pointer_modifier_ingress or features.client_overlay_input and features.client_overlay_scenes and features.workspace_panels %}";
        let direct = "{% if features.client_overlay_input and features.client_overlay_scenes and features.workspace_panels %}";
        if selected_source.path == SOURCES[1].path {
            ensure!(
                original.matches(pair).count() == 3,
                "pointer/overlay boundary count changed"
            );
            original = original.replace(
                pair,
                "{% if features.client_overlay_input or features.pointer_modifier_ingress %}",
            );
        }
        ensure!(
            original.matches(direct).count() == 3,
            "overlay boundary count changed"
        );
        original = original.replace(direct, "{% if features.client_overlay_input %}");
        return verify_template(original.as_bytes(), selected_source);
    }
    if selected_source.path != RESOURCE {
        return verify_template(bytes, selected_source);
    }
    ensure!(
        bytes.len() == 1625
            && sha256(bytes)
                == "sha256:56d025c4d4bc0a411bc20cdb136f080f1c372aeed5064e0f25c36cd9dc07fc83",
        "current mixin registration exceeded the one reviewed owner guard"
    );
    let text = std::str::from_utf8(bytes)?;
    let current = "{% if features.single_line_input or features.typed_command_palette or features.document_history %}";
    ensure!(
        text.matches(current).count() == 1,
        "current mixin guard is not unique"
    );
    let historical = text.replacen(
        current,
        "{% if features.single_line_input or features.typed_command_palette %}",
        1,
    );
    verify_template(historical.as_bytes(), selected_source)
}
fn verify_template(bytes: &[u8], selected_source: Source) -> Result<()> {
    ensure!(
        bytes.len() == selected_source.template_bytes
            && sha256(bytes) == selected_source.template_sha256
            && !bytes.contains(&b'\r')
            && bytes.ends_with(b"\n"),
        "mixin authored template drift"
    );
    std::str::from_utf8(bytes)?;
    Ok(())
}
