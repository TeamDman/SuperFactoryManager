impl Isolated {
    fn prepare(&self, context: &ProjectionContext) -> Result<BTreeMap<String, Vec<u8>>> {
        let target = target_id(context);
        for output in REQUIRED_PROJECT_FILES {
            let bytes = match *output {
                "gradle.properties" => format!(
                    "minecraft_version={}\nmod_version=source-fixture-only\n",
                    context.minecraft_version
                )
                .into_bytes(),
                "settings.gradle" => format!("rootProject.name = 'sfm-{target}'\n").into_bytes(),
                "gradle/wrapper/gradle-wrapper.properties" => {
                    b"distributionUrl=https\\://example.invalid/gradle-7.5-bin.zip\n".to_vec()
                }
                "gradle/wrapper/gradle-wrapper.jar" => b"\0\xff\x01source-fixture-only".to_vec(),
                _ => b"source-fixture-only\n".to_vec(),
            };
            write_fixture(
                &self.root,
                &format!("build/isolated-mixin-source-fixture/{output}"),
                &bytes,
            )?;
        }
        let inventory = discover_core_source_files(&self.root)?;
        let selection = select_core_inputs(&self.metadata, context, &inventory)?;
        let artifacts = collect_core_artifacts(&self.root, &selection, context)?;
        let mut outputs = BTreeMap::new();
        for selected_source in SOURCES {
            if let Some(artifact) = artifacts.get(selected_source.path) {
                let selected = &selection.inputs[selected_source.path];
                ensure!(
                    selected.input == selected_source.path
                        && selected.template == current_rule(selected_source).template
                        && artifact.source_path == format!("{CORE_ROOT}/{}", selected_source.path)
                        && artifact.overlay.is_none(),
                    "mixin input owner or rendering mode drift: {}",
                    selected_source.path
                );
                let source_text = std::str::from_utf8(&artifact.source_bytes)?;
                let actual = if selected_source.path == RESOURCE {
                    ensure!(
                        !artifact.output_bytes.starts_with(JAVA_BANNER),
                        "Java banner contaminated JSON"
                    );
                    artifact.output_bytes.clone()
                } else {
                    artifact
                        .output_bytes
                        .strip_prefix(JAVA_BANNER)
                        .ok_or_else(|| eyre::eyre!("Java renderer banner missing"))?
                        .to_vec()
                };
                ensure!(
                    actual == render_java_source(source_text, context)?.as_bytes(),
                    "collector bypassed actual controlled renderer"
                );
                outputs.insert(selected_source.path.to_owned(), actual);
            } else {
                ensure!(
                    selection.omitted_paths.contains(selected_source.path),
                    "unowned mixin source absence"
                );
            }
        }
        Ok(outputs)
    }
}
