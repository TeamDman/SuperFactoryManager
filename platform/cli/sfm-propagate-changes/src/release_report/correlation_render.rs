//! Correlate exact unchanged source lines with per-method bytecode PCs.
use super::document::ReleaseReportDocument;
use super::render::escape;
use eyre::Result;
use eyre::ensure;
use std::collections::BTreeMap;
use std::fmt::Write as _;

fn alignment(before: &str, after: &str) -> Result<BTreeMap<usize, usize>> {
    let a: Vec<_> = before.lines().collect();
    let b: Vec<_> = after.lines().collect();
    ensure!(
        a.len().saturating_mul(b.len()) <= 1_000_000,
        "source alignment exceeds cell budget"
    );
    let mut lengths = vec![vec![0; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            lengths[i][j] = if a[i] == b[j] {
                lengths[i + 1][j + 1] + 1
            } else {
                lengths[i + 1][j].max(lengths[i][j + 1])
            };
        }
    }
    let (mut i, mut j) = (0, 0);
    let mut mapping = BTreeMap::new();
    while i < a.len() && j < b.len() {
        if a[i] == b[j] {
            mapping.insert(i + 1, j + 1);
            i += 1;
            j += 1;
        } else if lengths[i + 1][j] > lengths[i][j + 1] {
            i += 1;
        } else {
            j += 1;
        }
    }
    Ok(mapping)
}

fn line_entry(line: &str) -> Option<(usize, usize)> {
    let (source, pc) = line.trim().strip_prefix("line ")?.split_once(':')?;
    Some((source.parse().ok()?, pc.trim().parse().ok()?))
}

fn entries(raw: &str) -> BTreeMap<(String, usize), usize> {
    let mut method = String::new();
    let mut result = BTreeMap::new();
    for line in raw.lines() {
        if line.starts_with("  ") && !line.starts_with("    ") && line.trim().ends_with(';') {
            line.trim().clone_into(&mut method);
        }
        if let Some((source, pc)) = line_entry(line) {
            result.insert((method.clone(), pc), source);
        }
    }
    result
}

fn represented_remainder(raw: &str) -> String {
    raw.lines()
        .filter(|line| line_entry(line).is_none())
        .collect::<Vec<_>>()
        .join("\n")
}

pub(super) fn render(doc: &ReleaseReportDocument) -> Result<String> {
    let mut html = String::new();
    for item in &doc.correlations {
        let source = doc
            .diffs
            .iter()
            .find(|d| d.id == item.source_diff_id)
            .ok_or_else(|| eyre::eyre!("correlation source missing"))?;
        ensure!(
            item.id == "resource-quantity-cause"
                && item.class_path == "ca/teamdman/sfml/ast/ResourceQuantity.class",
            "unsupported source-causal profile"
        );
        ensure!(source.after.strip_prefix("// GENERATED by sfm-propagate-changes; edit the primary source or reconcile this file.\n") == Some(source.before.as_str()), "ResourceQuantity cause is not the exact one-comment insertion");
        let mapping = alignment(&source.before, &source.after)?;
        let old = entries(&item.before_javap);
        let new = entries(&item.after_javap);
        let mut rows = String::new();
        let (mut changed, mut explained) = (0, 0);
        for (key, line) in &old {
            let next = new.get(key);
            if next != Some(line) {
                changed += 1;
            }
            let matched = next.is_some() && mapping.get(line) == next;
            if matched && next != Some(line) {
                explained += 1;
            }
            let _ = write!(
                rows,
                "<tr><td>{}</td><td>{}</td><td>{line}</td><td>{}</td><td>{}</td></tr>",
                escape(&key.0),
                key.1,
                next.map_or_else(|| "missing".to_owned(), usize::to_string),
                if matched {
                    "Aligned unchanged source line"
                } else {
                    "Unexplained · inspect raw diff"
                }
            );
        }
        for ((method, pc), line) in new.iter().filter(|(key, _)| !old.contains_key(*key)) {
            let _ = write!(
                rows,
                "<tr><td>{}</td><td>{pc}</td><td>missing</td><td>{line}</td><td>Unexplained new entry</td></tr>",
                escape(method)
            );
        }
        let other_equal =
            represented_remainder(&item.before_javap) == represented_remainder(&item.after_javap);
        let (patch, _) = super::static_patch::render(
            &format!("{}-raw", item.id),
            &item.before_javap,
            &item.after_javap,
        )?;
        let _ = write!(
            html,
            "<section id=\"{}\"><h3>ResourceQuantity · Minecraft 1.21.1 source-to-debug correspondence</h3><p>The candidate source adds one generated-file comment before the package declaration. Exact source-line alignment accounts for {explained} of {changed} changed entries at matched method/PC coordinates. The represented non-line-entry text is {}. This is a causal correspondence in this javap view, not exhaustive class-attribute or behavioral equivalence.</p><p><a href=\"#{}\">See the one-insertion source diff</a>. The baseline is <a href=\"https://github.com/TeamDman/SuperFactoryManager/blob/f5366c79c823ff52712130e69dd9c8166c70bd14/platform/minecraft/src/main/java/ca/teamdman/sfml/ast/ResourceQuantity.java#L1-L30\">verified published source</a>; the candidate generated snapshot has no verified public permalink.</p><details><summary>Complete method/PC mapping and raw printed diff</summary><div class=\"mapping-table\"><table><thead><tr><th>Method</th><th>PC</th><th>Before line</th><th>After line</th><th>Correspondence</th></tr></thead><tbody>{rows}</tbody></table></div>{patch}</details><p>Only exact parsed line-table entries were set aside for the remainder comparison. Local-variable tables and all other printed text remain compared. The -c -p -s -l view does not exhaustively represent constants, annotations, stack maps or bootstrap attributes. All debug changes in other classes remain visible without a global shift filter.</p></section>",
            escape(&item.id),
            if other_equal {
                "equal"
            } else {
                "different; inspect unexplained differences"
            },
            escape(&item.source_diff_id)
        );
    }
    Ok(html)
}

#[cfg(test)]
mod tests {
    #[test]
    fn alignment_handles_local_insertions_and_deletions_without_global_shift() {
        let map = super::alignment(
            "package;\na();\nb();\nc();",
            "// generated\npackage;\na();\nextra();\nc();",
        )
        .unwrap();
        assert_eq!(map.get(&1), Some(&2));
        assert_eq!(map.get(&2), Some(&3));
        assert!(!map.contains_key(&3));
        assert_eq!(map.get(&4), Some(&5));
    }
    #[test]
    fn method_and_pc_are_required_and_other_debug_text_remains() {
        let raw = "  public void a();\n    LineNumberTable:\n      line 2: 0\n  public void b();\n      line 9: 0\n    LocalVariableTable:\n";
        let entries = super::entries(raw);
        assert_eq!(entries.len(), 2);
        assert_eq!(entries[&("public void b();".to_owned(), 0)], 9);
        assert!(super::represented_remainder(raw).contains("LocalVariableTable"));
    }
}
