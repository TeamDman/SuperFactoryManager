    static boolean platformStateAllowed(boolean initial, boolean mayDamagePlatform, BlockState actual) {
        return (!initial && mayDamagePlatform) || actual.is(Blocks.POLISHED_ANDESITE);
    }

    static boolean infrastructureStateAllowed(BlockState actual, Block expected,
                                               BlockEntity current, BlockEntity original) {
        return actual.is(expected) && original != null && current == original;
    }

