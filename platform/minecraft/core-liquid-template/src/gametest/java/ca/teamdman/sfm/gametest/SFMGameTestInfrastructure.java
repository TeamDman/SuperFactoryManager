    private void checkReserved(String phase, String kind, BlockPos pos, Block expected,
                               BlockState originalState, BlockEntity original, Object originalDetails,
                               Function<BlockEntity, Object> details) {
        BlockState actual = helper.getLevel().getBlockState(pos);
        BlockEntity current = helper.getLevel().getBlockEntity(pos);
        Object currentDetails = details.apply(current);
        if (!infrastructureStateAllowed(actual, expected, current, original)
                || !actual.equals(originalState) || !Objects.equals(currentDetails, originalDetails)) {
            helper.assertTrue(false, diagnostic(phase, kind + " block absolute=" + pos + " expected=" + originalState
                    + " entity=" + originalDetails + "; actual=" + actual + " entity=" + currentDetails));
        }
    }

