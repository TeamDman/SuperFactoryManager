#!/usr/bin/env python3
"""Generate the 20 portable fixtures and audit release-code identity. No build/download."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cli', type=Path, required=True)
    parser.add_argument('--repo-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    root = args.repo_root.resolve()
    catalog = json.loads((root / 'platform/minecraft/projections.json').read_text())
    keys = sorted(k for k in catalog if '-issue610-portable/' in k)
    assert len(keys) == 20, 'Expected two releases across ten supported versions'
    args.output.mkdir(parents=True, exist_ok=True)
    receipt_path = args.output / 'audit.json'
    receipt = {'status': 'running', 'cli_sha256': digest(args.cli.read_bytes()), 'projections': {}}
    receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
    try:
        command = [str(args.cli), 'source', 'project', 'manifest', '--repo-root', str(root)]
        for key in keys:
            command += ['--projection', key]
        with (args.output / 'generation.json').open('w') as out, (args.output / 'generation.stderr').open('w') as err:
            completed = subprocess.run(command, stdout=out, stderr=err, timeout=300)
        receipt['generation_exit'] = completed.returncode
        receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
        if completed.returncode:
            raise SystemExit(completed.returncode)
        energy = 'src/main/java/ca/teamdman/sfml/ast/OutputStatement.java'
        provider = 'src/main/java/ca/teamdman/sfm/common/capability/Issue610FixtureEnergyProvider.java'
        fixture = 'src/gametest/java/ca/teamdman/sfm/gametest/tests/regression/Issue610PortableControlsGameTest.java'
        scheduler = 'src/gametest/java/ca/teamdman/sfm/gametest/tests/compat/justdirethings/Issue610VisualControls.java'
        relay = 'src/main/java/ca/teamdman/sfm/common/capability/TunnelledBlockCapabilityRelay.java'
        header = b'// GENERATED by sfm-propagate-changes; edit the primary source or reconcile this file.\n'
        canonical_scheduler = header + (root / 'platform/minecraft/core-liquid-template' / scheduler).read_bytes()
        for key in keys:
            base = key.replace('-issue610-portable', '')
            command = [str(args.cli), 'source', 'render', '--repo-root', str(root), '--projection', base, '--file', energy]
            rendered = subprocess.run(command, capture_output=True, text=True, check=True, timeout=60)
            expected = (b'// GENERATED by sfm-propagate-changes; edit the primary source or reconcile this file.\n'
                        + json.loads(rendered.stdout)['rendered_content'].encode())
            projection = root / 'platform/minecraft/projections' / key
            actual = (projection / energy).read_bytes()
            assert actual == expected, key + ': transfer implementation differs from vanilla release'
            source = (projection / fixture).read_text()
            adapter = (projection / provider).read_text()
            fixed = key.startswith('sfm-4.35.0-')
            assert ('EXPECT_FIXED = true' if fixed else 'EXPECT_FIXED = false') in source, key
            assert (projection / scheduler).read_bytes() == canonical_scheduler, key + ': scheduler drift'
            assert 'ISSUE_610_FIXTURE = REGISTERER.register' in (projection / 'src/main/java/ca/teamdman/sfm/common/registry/registration/SFMGlobalBlockCapabilityProviders.java').read_text(), key
            assert all(text in source for text in ['RUN MANAGER', 'DRAIN SECOND', 'MANUAL MODE', 'Not Mekanism/JDT']), key
            version = key.split('/mc-')[1]
            modern = version in ['1.20.3', '1.20.4', '1.21.0', '1.21.1', '26.1.2']
            assert (projection / relay).exists() == (fixed and modern), key + ': invalidation boundary drift'
            if version == '26.1.2':
                assert 'SimpleEnergyHandler' in adapter and 'TransactionContext' in adapter and 'EnergyStorage' not in adapter
            elif version in ['1.19.2', '1.19.4', '1.20', '1.20.1']:
                assert 'net.minecraftforge.energy.EnergyStorage' in adapter and 'TransactionContext' not in adapter
            else:
                assert 'net.neoforged.neoforge.energy.EnergyStorage' in adapter and 'TransactionContext' not in adapter
            receipt['projections'][key] = {'generated': True, 'energy_matches': base,
                'energy_sha256': digest(actual), 'fixture_sha256': digest(source.encode()),
                'provider_sha256': digest(adapter.encode()), 'expected': 'refill' if fixed else 'starvation',
                'native_relay_selected': fixed and modern, 'compiled': False, 'automated_world_passed': False,
                'manual_live_verified': False}
            receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
        receipt['status'] = 'passed'
        receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
        print('Generated and audited 20 projections; OutputStatement identity verified for every release pair.')
    except BaseException as error:
        receipt['status'] = 'failed'
        receipt['error'] = str(error)
        receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
        raise



if __name__ == '__main__':
    main()
